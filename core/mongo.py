"""
MongoDB connection (MES events, batches, WIP, scrap, downtime, measurements,
ID counters). One shared client per process.

Collections and their indexes are declared in COLLECTIONS so that
`python manage.py init_mongo` can create them on a fresh database.
"""
import logging
import os
from functools import lru_cache

from pymongo import ASCENDING, DESCENDING, MongoClient

logger = logging.getLogger("app")

# collection -> list of (keys, options)
COLLECTIONS = {
    "counters": [],
    "work_orders": [([("wo_id", ASCENDING)], {"unique": True}),
                    ([("status", ASCENDING), ("due_date", ASCENDING)], {})],
    "batches": [([("batch_id", ASCENDING)], {"unique": True}),
                ([("wo_id", ASCENDING)], {})],
    "wip": [([("wip_id", ASCENDING)], {"unique": True}),
            ([("batch_id", ASCENDING), ("step_no", ASCENDING)], {}),
            ([("workstation", ASCENDING), ("status", ASCENDING)], {})],
    # Every worker/gateway action. event_id is generated by the client, so a
    # replayed offline queue can never be counted twice.
    "step_events": [([("event_id", ASCENDING)], {"unique": True}),
                    ([("wip_id", ASCENDING), ("ts", ASCENDING)], {}),
                    ([("type", ASCENDING), ("ts", DESCENDING)], {}),
                    ([("workstation", ASCENDING), ("ts", DESCENDING)], {})],
    "scans": [([("event_id", ASCENDING)], {"unique": True}),
              ([("workstation", ASCENDING), ("ts", DESCENDING)], {})],
    "device_health": [([("device_id", ASCENDING)], {"unique": True})],
}


def mongo_uri():
    return os.environ.get("MONGO_URI", "mongodb://127.0.0.1:27032/?directConnection=true")


@lru_cache(maxsize=1)
def client():
    logger.info("Connecting to MongoDB at %s", mongo_uri().split("@")[-1])
    return MongoClient(mongo_uri(), serverSelectionTimeoutMS=3000, tz_aware=True)


def db():
    return client()[os.environ.get("MONGO_DB", "threeform_mes")]


def ensure_indexes(database=None):
    database = database if database is not None else db()
    for name, indexes in COLLECTIONS.items():
        coll = database[name]
        for keys, opts in indexes:
            coll.create_index(keys, **opts)
        logger.info("Mongo collection ready: %s (%d indexes)", name, len(indexes))


def ping():
    try:
        client().admin.command("ping")
        return True
    except Exception as exc:  # noqa: BLE001 - health check must never raise
        logger.warning("MongoDB ping failed: %s", exc)
        return False
